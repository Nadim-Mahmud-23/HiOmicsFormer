"""
Assemble r2/nbdefs.py from the notebook's DEFINITIONAL cells verbatim.

We reuse the exact class code from HiOmicsFormer_Revised_R1_Final.ipynb (extracted
into .r2_cells/cell_NN.py) rather than re-implementing it, per the revision brief's
"reuse, don't recreate" rule. Trailing *execution* / plotting blocks are stripped so
importing nbdefs has no side effects beyond defining classes + `config`.

The ONLY additive change is a leakage-free `MultiOmicsPreprocessor.transform()`
method (Phase 6 refactor): it applies the ALREADY-FITTED feature selection (by name)
and scaler statistics to new data, with no refit. fit_transform is untouched.
"""
import os

CELLS = os.path.join(os.path.dirname(__file__), "..", ".r2_cells")


def read(n):
    with open(os.path.join(CELLS, f"cell_{n:02d}.py")) as fh:
        return fh.read()


def truncate_before(text, marker):
    i = text.find(marker)
    if i == -1:
        raise SystemExit(f"marker not found: {marker!r}")
    return text[:i].rstrip() + "\n"


# ---- transform() method, appended INSIDE MultiOmicsPreprocessor (method-level indent) ----
TRANSFORM_METHOD = '''
    def transform(self, omics_data):
        """Apply the ALREADY-FITTED selection + scaler to new data (no refit).

        Phase 6 (Reviewer 1.3) refactor: reuses the fitted per-modality feature
        names and StandardScaler statistics so an external cohort can be projected
        into TCGA feature space WITHOUT leakage. Missing / absent features are
        filled with the fitted per-feature mean (i.e. 0 after z-scoring), exactly
        matching what the scaler saw at fit time. fit_transform is unchanged.
        """
        if not self.fitted:
            raise RuntimeError("Preprocessor not fitted; call fit_transform first.")
        processed = {}
        for mod in omics_data:
            names = self.feature_names.get(mod)
            if not names:
                continue
            df = omics_data[mod]
            aligned = df.reindex(columns=names)          # select fitted features by name
            X = aligned.values.astype(np.float32)
            scaler = self.scalers[mod]
            means = np.asarray(scaler.mean_, dtype=np.float32)
            nan_r, nan_c = np.where(np.isnan(X))
            if len(nan_r):
                X[nan_r, nan_c] = means[nan_c]           # fitted-mean fill (leakage-free)
            processed[mod] = scaler.transform(X).astype(np.float32)
        return processed
'''


def build():
    parts = []
    parts.append(
        "# ==========================================================================\n"
        "# AUTO-GENERATED by r2/_build_nbdefs.py from HiOmicsFormer_Revised_R1_Final.ipynb\n"
        "# Definitional cells only (classes + config). DO NOT EDIT BY HAND.\n"
        "# The one additive change is MultiOmicsPreprocessor.transform() (see build script).\n"
        "# ==========================================================================\n"
    )
    # Force headless plotting before pyplot is imported by cell 1.
    parts.append("import matplotlib\nmatplotlib.use('Agg')\n")

    parts.append(read(1))   # imports, seeds, device
    parts.append(read(2))   # config dataclass + `config = HiOmicsConfig()`

    # MLOmicsDataLoader class only (drop the "# ---------- Execute ----------" block)
    parts.append(truncate_before(read(3), "# ---------- Execute ----------"))

    # MultiOmicsPreprocessor class only + append transform(); drop trailing execution
    prep = truncate_before(read(5), '\nprint("Preprocessing omics data')
    parts.append(prep)
    parts.append(TRANSFORM_METHOD)

    # MultiOmicsDataset class only (drop `full_dataset = ...` execution)
    parts.append(truncate_before(read(7), "\nfull_dataset = MultiOmicsDataset"))

    # Model classes only (drop `# Verify architecture matches Table 2` execution)
    parts.append(truncate_before(read(8), "\n# Verify architecture matches Table 2"))

    parts.append(read(9))   # HiOmicsLoss (+ harmless prints)
    parts.append(read(10))  # HiOmicsTrainer + init_centroids (+ harmless print)

    # AttentionBiomarkerExtractor class only (drop "# --- Execute on full dataset ---")
    parts.append(truncate_before(read(17), "# --- Execute on full dataset ---"))

    # Baseline functions only (drop "# --- Run all baselines on same CV splits ---")
    parts.append(truncate_before(read(14), "# --- Run all baselines on same CV splits ---"))

    out = os.path.join(os.path.dirname(__file__), "nbdefs.py")
    with open(out, "w") as fh:
        fh.write("\n\n".join(p.rstrip() + "\n" for p in parts))
    print("wrote", out)


if __name__ == "__main__":
    build()
