RES = "results_revision"; FIG = "figures_revision"


def jload(name, default=None):
    p = os.path.join(RES, name)
    if os.path.exists(p):
        try:
            return json.load(open(p))
        except Exception:
            return default
    return default


def cload(name):
    p = os.path.join(RES, name)
    return pd.read_csv(p) if os.path.exists(p) else None


def fmt_imp(csv):
    df = cload(csv)
    if df is None:
        return "pending"
    rows = []
    for mod in ["mRNA", "miRNA", "Methy", "CNV"]:
        sub = df[df.modality == mod]
        if len(sub):
            rows.append(f"{mod} J={sub.jaccard.mean():.2f}(chance {sub.null_jaccard.mean():.3f}), "
                        f"raw {sub.raw_missing.iloc[0]:.0%}/eff {sub.eff_missing.iloc[0]:.0%}")
    return "; ".join(rows)


